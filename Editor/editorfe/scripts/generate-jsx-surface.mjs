// Writes the list of JSX tags and attributes that the AI code check uses, as a
// Swift file and a Kotlin file. Run by `npm run docs`.
//
// The names are the union of Studio's API metadata and the web renderer's
// coverage table, so that an attribute either of them knows is never reported.
// The closed lists of values come from the metadata.
//
// The native JSX switch stays the runtime authority. This list only lets the
// apps tell a model "there is no such attribute" before a widget is run, because
// the runtime ignores an unknown attribute without an error.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { scriptWidgetAPI as api } from "../src/scriptWidgetAPI.js";
// Every attribute a native builder reads; its own test derives the list from the Swift sources.
import { coverage, generalProps } from "../../../Web/preview-engine/src/render/coverage.js";

// Attributes whose values the runtime reads from a closed list and silently
// replaces when they are not in it. Only these have their values checked; an
// attribute such as `font` also takes forms the metadata does not list.
const closedValues = new Set([
  "*.fontWeight", "*.fontDesign", "*.backgroundMaterial", "*.clip",
  "Date.style", "Image.mode", "Divider.axis", "Line.axis", "Progress.style",
]);

// Names the runtime reads that the metadata does not list.
const extraGlobals = { weight: api.globalProperties.fontWeight.values, key: null };

// Tags that only one system has: [system, tag, attributes].
const platformTags = [["android", "list", ["spacing"]]];

function entry(owner, name, property) {
  const values = closedValues.has(`${owner}.${name}`) ? property?.values : null;
  return values?.length ? `${name}=${values.join("|")}` : name;
}

export function jsxSurfaceText() {
  const lines = [];
  const globals = new Map(Object.entries(api.globalProperties).map(([name, property]) => [name, entry("*", name, property)]));
  for (const name of Object.keys(generalProps)) if (!globals.has(name)) globals.set(name, name);
  for (const [name, values] of Object.entries(extraGlobals)) globals.set(name, values ? `${name}=${values.join("|")}` : name);
  for (const text of globals.values()) lines.push(`global ${text}`);

  const tags = new Map();
  for (const [name, component] of Object.entries(api.components)) {
    tags.set(name.toLowerCase(), new Map(Object.entries(component.properties ?? {}).map(([key, property]) => [key, entry(name, key, property)])));
  }
  for (const [name, row] of Object.entries(coverage.tags)) {
    if (name !== name.toLowerCase()) continue; // Fragment is not written as a tag
    const properties = tags.get(name) ?? new Map();
    for (const key of Object.keys(row.props ?? {})) if (!properties.has(key) && !globals.has(key)) properties.set(key, key);
    tags.set(name, properties);
  }
  for (const [name, properties] of tags) lines.push(["tag", name, ...properties.values()].join(" "));
  for (const [system, name, properties] of platformTags) lines.push([`tag@${system}`, name, ...properties].join(" "));
  return lines.join("\n");
}

const note = "Generated by Editor/editorfe/scripts/generate-jsx-surface.mjs from scriptWidgetAPI.js and coverage.js. Do not edit; run `npm run docs` in Editor/editorfe.";

export const outputs = {
  "Shared/ScriptWidgetRuntime/AI/AIJSXSurfaceData.swift": () => `//
//  AIJSXSurfaceData.swift
//  ScriptWidget
//
//  ${note}
//

enum AIJSXSurfaceData {
    /// One line per general attribute ("global") and per tag ("tag"). An
    /// attribute with a closed list of values is written name=a|b|c.
    static let text = """
${jsxSurfaceText().split("\n").map((line) => `    ${line}`).join("\n")}
    """
}
`,
  "Android/core/src/main/java/com/everettjf/scriptwidget/core/ai/AiJsxSurfaceData.kt": () => `package com.everettjf.scriptwidget.core.ai

// ${note}

internal object AiJsxSurfaceData {
    /** One line per general attribute ("global") and per tag ("tag"). An attribute with a closed list of values is written name=a|b|c. */
    val TEXT = """
${jsxSurfaceText()}
""".trim()
}
`,
};

export const repositoryRoot = new URL("../../../", import.meta.url);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, content] of Object.entries(outputs)) await writeFile(new URL(path, repositoryRoot), content());
}

// For the test that the checked-in files are current.
export async function staleOutputs() {
  const stale = [];
  for (const [path, content] of Object.entries(outputs)) {
    const current = await readFile(new URL(path, repositoryRoot), "utf8").catch(() => "");
    if (current !== content()) stale.push(path);
  }
  return stale;
}
