// Generates the JavaScript assets the Linux runtime shares with the web
// preview engine, the Android app and the Windows app. Run after changing
// Web/preview-engine/src, the support bundle, or Android/core/src/main/js:
//
//   node Linux/scripts/build-shared-js.mjs
//
// Output (not checked in): Linux/assets/scriptwidget/ and the parity corpus
// in Linux/tests/assets/.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { buildSharedJS, repository } from "../../Scripts/lib/shared-js.mjs";

await buildSharedJS({
  output: path.join(repository, "Linux/assets/scriptwidget"),
  banner: "// Generated by Linux/scripts/build-shared-js.mjs. Do not edit.\n",
  compilerFingerprint: "scriptwidget-linux-babel-v1",
  // The QuickJS host files are shared with Android and Windows. API files
  // are evaluated in name order after host.js; the fallbacks in apis.js come
  // last.
  hostFiles: [
    ["android-host.js", "host.js"],
    ["android-apis-datasource.js", "apis-10-datasource.js"],
    ["android-apis-weather.js", "apis-20-weather.js"],
    ["android-apis.js", "apis-90.js"],
    ["android-compiler.js", "compiler.js"],
  ],
  // The Android directory keeps the module paths inside render.js identical
  // to the Android and Windows bundles.
  bundleDirectory: path.join(repository, "Android"),
  corpusOutput: path.join(repository, "Linux/tests/assets"),
});

// What the management window's code editor completes from: the metadata the
// other editors use (Editor/editorfe/src/scriptWidgetAPI.js), as data, the
// way Windows/scripts/build-shared-js.mjs writes it. Linux/crates/sw-studio
// builds it into the program (see its build.rs).
const { scriptWidgetAPI } = await import(pathToFileURL(path.join(repository, "Editor/editorfe/src/scriptWidgetAPI.js")).href);
fs.writeFileSync(
  path.join(repository, "Linux/assets/scriptwidget/api-reference.json"),
  JSON.stringify({ functions: scriptWidgetAPI.functions, components: scriptWidgetAPI.components, globalProperties: scriptWidgetAPI.globalProperties }) + "\n",
);
