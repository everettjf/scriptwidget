using System.Text.Json.Nodes;
using ScriptWidget.Core.Hosting;

namespace ScriptWidget.Studio.Services;

/// <summary>One function a widget's code can call, as the reference shows it.</summary>
public sealed class ApiFunction
{
    public required string Group { get; init; }
    /// <summary><c>$storage.setString(key, value) → boolean</c></summary>
    public required string Signature { get; init; }
    public required string Documentation { get; init; }
    public Microsoft.UI.Xaml.Visibility DocumentationVisibility => Documentation.Length > 0 ? Microsoft.UI.Xaml.Visibility.Visible : Microsoft.UI.Xaml.Visibility.Collapsed;
}

/// <summary>One global such as <c>$storage</c>, with its functions and its bundled example when there is one.</summary>
public sealed class ApiGroup
{
    public required string Name { get; init; }
    public required IReadOnlyList<ApiFunction> Functions { get; init; }
    /// <summary>False for a global Windows does not implement in this release.</summary>
    public required bool Supported { get; init; }
    public BundledPackage? Example { get; init; }
    public string Caption => !Supported ? Loc.T("apis.notOnWindows") : Functions.Count == 0 ? Loc.T("apis.exampleOnly") : Functions.Count == 1 ? Loc.T("apis.function") : Loc.T("apis.functions", Functions.Count);
    public double NameOpacity => Supported ? 1.0 : 0.55;
}

/// <summary>One property of a component.</summary>
public sealed class ComponentProperty
{
    public required string Name { get; init; }
    /// <summary>The type, with the allowed values of an enumeration and "required" when it must be given.</summary>
    public required string Type { get; init; }
    public required string Documentation { get; init; }
    public Microsoft.UI.Xaml.Visibility DocumentationVisibility => Documentation.Length > 0 ? Microsoft.UI.Xaml.Visibility.Visible : Microsoft.UI.Xaml.Visibility.Collapsed;
}

/// <summary>What the reference knows about a component example.</summary>
public sealed record ComponentInfo(string Documentation, IReadOnlyList<ComponentProperty> Properties, IReadOnlyList<string> CommonAttributes);

/// <summary>
/// The API reference of the management window. The data is generated by
/// <c>Windows/scripts/build-shared-js.mjs</c> from the metadata the code editor
/// completes from, so the two cannot disagree.
/// </summary>
public static class ApiReference
{
    private static readonly Lazy<JsonObject?> Data = new(() =>
    {
        try { return JsonNode.Parse(File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "assets", "scriptwidget", "api-reference.json"))) as JsonObject; }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException or System.Text.Json.JsonException) { return null; }
    });

    private static string Text(JsonObject? item, string key) => item?[key] is JsonValue value && value.TryGetValue<string>(out var text) ? text : "";

    /// <summary>The globals in the order: usable on Windows, examples without a reference entry, not on Windows.</summary>
    public static IReadOnlyList<ApiGroup> Groups(IReadOnlyList<BundledPackage> bundled)
    {
        var examples = bundled.Where(item => item.Group == "api").ToDictionary(item => item.Name, StringComparer.OrdinalIgnoreCase);
        var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var functions = new Dictionary<string, List<ApiFunction>>(StringComparer.Ordinal);
        var order = new List<string>();
        foreach (var (id, node) in Data.Value?["functions"] as JsonObject ?? new JsonObject())
        {
            var entry = node as JsonObject;
            var group = id.Contains('.') ? id[..id.IndexOf('.')] : id;
            if (!functions.TryGetValue(group, out var list)) { functions[group] = list = new List<ApiFunction>(); order.Add(group); }
            var arguments = entry?["arguments"] is JsonArray array ? string.Join(", ", array.Select(item => item?.ToString() ?? "")) : "…";
            var returns = Text(entry, "returns");
            list.Add(new ApiFunction { Group = group, Signature = $"{id}({arguments})" + (returns.Length > 0 ? " → " + returns : ""), Documentation = Text(entry, "documentation") });
        }
        var result = new List<ApiGroup>();
        foreach (var name in order)
        {
            var bare = name.TrimStart('$');
            var exampleName = bare == "importJS" ? "import" : bare;
            examples.TryGetValue(exampleName, out var example);
            if (example is not null) used.Add(example.Name);
            result.Add(new ApiGroup { Name = name, Functions = functions[name], Supported = !Library.IsUnsupportedApi(bare), Example = example });
        }
        // Examples of things that are not functions of a global: console, $getenv, animations…
        foreach (var example in examples.Values.Where(item => !used.Contains(item.Name)).OrderBy(item => item.Name, StringComparer.OrdinalIgnoreCase))
        {
            result.Add(new ApiGroup { Name = example.Name, Functions = [], Supported = true, Example = example });
        }
        return result.OrderBy(group => !group.Supported ? 2 : group.Functions.Count == 0 ? 1 : 0).ToList();
    }

    /// <summary>
    /// The reference entry for a component example: <c>vstack</c> is the component <c>VStack</c>,
    /// <c>attribute-frame</c> is the attribute <c>frame</c> every component takes.
    /// </summary>
    public static ComponentInfo? Component(string exampleName)
    {
        var data = Data.Value;
        if (data is null) return null;
        var common = (data["globalProperties"] as JsonObject)?.Select(item => item.Key).ToList() ?? [];
        if (exampleName.StartsWith("attribute-", StringComparison.OrdinalIgnoreCase))
        {
            var attribute = exampleName["attribute-".Length..];
            var found = (data["globalProperties"] as JsonObject)?.FirstOrDefault(item => item.Key.Equals(attribute, StringComparison.OrdinalIgnoreCase));
            return found is { Value: JsonObject property } ? new ComponentInfo("", [Property(found.Value.Key, property)], []) : null;
        }
        var match = (data["components"] as JsonObject)?.FirstOrDefault(item => item.Key.Equals(exampleName, StringComparison.OrdinalIgnoreCase));
        if (match is not { Value: JsonObject component }) return null;
        var properties = (component["properties"] as JsonObject)?.Where(item => item.Value is JsonObject).Select(item => Property(item.Key, (JsonObject)item.Value!)).ToList() ?? [];
        return new ComponentInfo(Text(component, "documentation"), properties, common);
    }

    private static ComponentProperty Property(string name, JsonObject property)
    {
        var type = Text(property, "type");
        if (property["values"] is JsonArray values && values.Count > 0) type = string.Join(" | ", values.Select(item => item?.ToString() ?? ""));
        if (property["required"] is JsonValue required && required.TryGetValue<bool>(out var must) && must) type += "  ·  " + Loc.T("detail.required");
        return new ComponentProperty { Name = name, Type = type, Documentation = Text(property, "documentation") };
    }
}
