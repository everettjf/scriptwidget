// Generates the JavaScript assets the Windows runtime shares with the web
// preview engine and the Android app. Run after changing
// Web/preview-engine/src, the support bundle, or Android/core/src/main/js:
//
//   node Windows/scripts/build-shared-js.mjs
//
// Output (not checked in): Windows/assets/scriptwidget/ and the parity
// corpus in Windows/tests/assets/.
import path from "node:path";
import { buildSharedJS, repository } from "../../Scripts/lib/shared-js.mjs";

await buildSharedJS({
  output: path.join(repository, "Windows/assets/scriptwidget"),
  banner: "// Generated by Windows/scripts/build-shared-js.mjs. Do not edit.\n",
  compilerFingerprint: "scriptwidget-windows-babel-v1",
  // The QuickJS host files are shared with Android. API files are evaluated
  // in name order after host.js; the fallbacks in apis.js come last.
  hostFiles: [
    ["android-host.js", "host.js"],
    ["android-apis-datasource.js", "apis-10-datasource.js"],
    ["android-apis-weather.js", "apis-20-weather.js"],
    ["android-apis.js", "apis-90.js"],
    ["android-compiler.js", "compiler.js"],
  ],
  // The Android directory keeps the module paths inside render.js identical
  // to the Android bundle.
  bundleDirectory: path.join(repository, "Android"),
  corpusOutput: path.join(repository, "Windows/tests/assets"),
});
