// Generates the JavaScript assets the Android runtime shares with the web
// preview engine. Run after changing Web/preview-engine/src, the support
// bundle, or Android/core/src/main/js:
//
//   node Android/scripts/build-shared-js.mjs
//
// Output (checked in): Android/core/src/main/assets/scriptwidget/
// Output (not checked in): the parity corpus used by instrumented tests.
import fs from "node:fs";
import path from "node:path";
import { buildSharedJS, repository, hostSources } from "../../Scripts/lib/shared-js.mjs";

await buildSharedJS({
  output: path.join(repository, "Android/core/src/main/assets/scriptwidget"),
  banner: "// Generated by Android/scripts/build-shared-js.mjs. Do not edit.\n",
  compilerFingerprint: "scriptwidget-android-babel-v1",
  hostFiles: fs.readdirSync(hostSources).filter((file) => file.endsWith(".js")).sort().map((file) => [file, file]),
  // esbuild writes each module's path relative to the working directory into the bundle, so the
  // directory is fixed: the output is the same wherever the script is started from.
  bundleDirectory: path.join(repository, "Android"),
  corpusOutput: path.join(repository, "Android/core/src/androidTest/assets"),
});
